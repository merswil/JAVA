public class Creating_Variables_and_Naming_Them {

    public static String mybyte(){
        byte value = 10;
        return value + " is a byte";
    }
    public static String myshort(){
        short value = 1000;
        return value + " is a short";
    }
    public static String myint(){
        int value = 10;
        return value + " is an int";
    }
    public static String mylong(){
        long value = 10000000000L;
        return value + " is a long";
    }
    public static String myfloat(){
        float value = 10.0f;
        return value + " is a float";
    }
    public static String mydouble(){
        double value = 10.0;
        return value + " is a double";
    }
    public static String myboolean(){
        boolean value = true;
        return value + " is a boolean";
    }
    public static String mychar(){
        char value = 'D';
        return value + " is a char";
    }
    public static String mystring(){
        String value = "Hello";
        return value + " is a String";
    }
}